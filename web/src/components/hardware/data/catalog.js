/**
 * Type (yoki LT id/partNum) bo'yicha katalog elementini topish.
 */
export function getCatalogEntry(type) {
  // 1. Asosiy katalogdan qidirish
  const mainEntry = CATALOG.find(c => c.type === type || c.partNum === type);
  if (mainEntry) return mainEntry;

  // 2. LEGO Technic parts ro'yxatidan qidirish
  const ltPart = LEGO_TECHNIC_PARTS.find(p => p.id === type || p.partNum === type);
  if (ltPart) {
    const generatorType = ltPart.generator || 'lego_beam';
    return {
      type: ltPart.id,
      name: `${ltPart.name} (${ltPart.color})`,
      description: `Part #${ltPart.partNum || 'N/A'} - ${ltPart.color}`,
      isProcedural: ltPart.modelType === 'procedural',
      modelType: ltPart.modelType,
      file: ltPart.file,
      filename: ltPart.file,
      generatorType: generatorType,
      category: 'all_lego',
      defaultParams: { ...(ltPart.params || {}), scalePercent: 100 },
      material: {
        color: ltPart.colorHex || '#38bdf8',
        metalness: 0.2,
        roughness: 0.4,
        envMapIntensity: 1.0,
      },
    };
  }

  return undefined;
}

export function getMaterialConfig(type) {
  const entry = getCatalogEntry(type);
  const defaultMat = { color: '#38bdf8', metalness: 0.2, roughness: 0.3, envMapIntensity: 1.0 };
  if (entry && entry.material) {
    return { ...defaultMat, ...entry.material };
  }
  return defaultMat;
}

/**
 * Detal nomini joriy tilga mos ravishda olish (SPEC.md §8 / I18N_SPEC.md §3.1)
 */
export function getPartName(entry, lang = 'uz') {
  if (!entry) return '';
  if (lang === 'ru') return entry.nameRu || entry.name;
  if (lang === 'en') return entry.nameEn || entry.name;
  return entry.name;
}

/**
 * Detal texnik tavsifini joriy tilga mos ravishda olish
 */
export function getPartSpecs(entry, lang = 'uz') {
  if (!entry) return '';
  if (lang === 'ru') return entry.specsRu || entry.specs || entry.description || '';
  if (lang === 'en') return entry.specsEn || entry.specs || entry.description || '';
  return entry.specs || entry.description || '';
}

